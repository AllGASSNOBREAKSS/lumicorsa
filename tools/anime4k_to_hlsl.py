#!/usr/bin/env python3
"""Converts an Anime4K v4 restore CNN (mpv GLSL hook file, MIT, bloc97) into CSP Lua-shader passes.

Each GLSL pass becomes one HLSL file for ui.ExtraCanvas:updateWithShader(). The layers are 3x3 convolutions with
CReLU between them, so every pass reads one 4-channel texture and writes one. GLSL `mat4(a0..a15) * v` fills the
matrix by columns, which is exactly HLSL `mul(v, float4x4(a0..a15))` (rows), so weights are copied in file order.

usage: anime4k_to_hlsl.py <Anime4K_Restore_CNN_*.glsl> <out_dir> <prefix>
"""
import pathlib, re, sys

NUM = r'-?\d+(?:\.\d+)?(?:[eE][-+]?\d+)?'


def parse(path):
    """Returns a list of passes: {relu: bool, taps: [(x, y, chan_sign, [16 floats])], bias: [4], residual: bool}."""
    text = pathlib.Path(path).read_text(encoding='utf-8')
    passes = []
    for block in text.split('//!DESC')[1:]:
        defs = dict(re.findall(r'#define (go_\d)\(x_off, y_off\) \((.*)\)\n', block))
        if not defs:
            continue
        taps = []
        for args, go, x, y in re.findall(r'mat4\(([^)]*)\) \* (go_\d)\((' + NUM + r'), (' + NUM + r')\)', block):
            w = [float(v) for v in args.split(',')]
            assert len(w) == 16, block[:80]
            d = defs[go]
            if d.startswith('max(-('):
                sign, relu = -1, True
            elif d.startswith('max(('):
                sign, relu = 1, True
            else:
                sign, relu = 1, False
            taps.append((float(x), float(y), sign, relu, w))
        bias = [float(v) for v in re.search(r'result \+= vec4\(([^)]*)\);', block).group(1).split(',')]
        relus = {t[3] for t in taps}
        assert len(relus) == 1, 'mixed activation in one pass'
        passes.append({
            'relu': relus.pop(),
            'taps': [(x, y, s, w) for x, y, s, _, w in taps],
            'bias': bias,
            'residual': 'MAIN_tex(MAIN_pos)' in block,
            'desc': block.splitlines()[0].strip(),
        })
    return passes


def fmt(v):
    s = repr(float(v))
    return s if 'e' in s or '.' in s else s + '.0'


def emit(p, index, source_name):
    out = [f'// Photolap Neural, layer {index}: {p["desc"]}',
           f'// Generated by tools/anime4k_to_hlsl.py from {source_name} (Anime4K, MIT License, (c) 2019-2021 bloc97).',
           '// @textures txPLIn' + (' txPLBase' if p['residual'] else ''),
           '// @values gPLTexel:float2' + (' gPLIntensity:float' if p['residual'] else ''),
           'float4 main(PS_IN pin) {',
           '  float2 uv = pin.Tex;',
           f'  float4 r = float4({", ".join(fmt(b) for b in p["bias"])});',
           '  float4 s;']
    by_off = {}
    for x, y, sign, w in p['taps']:
        by_off.setdefault((x, y), []).append((sign, w))
    for (x, y), items in by_off.items():
        out.append(f'  s = txPLIn.SampleLevel(samPointClamp, uv + float2({fmt(x)}, {fmt(y)}) * gPLTexel, 0);')
        for sign, w in items:
            if not p['relu']:
                v = 's'
            else:
                v = 'max(s, 0.0)' if sign > 0 else 'max(-s, 0.0)'
            out.append(f'  r += mul({v}, float4x4({", ".join(fmt(a) for a in w)}));')
    if p['residual']:
        # On game frames the restore net's residual is an edge-aware smoothing step. Subtracting it is a learned
        # unsharp mask: detail goes up where the net sees structure, and the clamp keeps halos in check.
        out.append('  float3 base = txPLBase.SampleLevel(samPointClamp, uv, 0).rgb;')
        out.append('  return float4(base - clamp(r.rgb * gPLIntensity, -0.12, 0.12), 1.0);')
    else:
        out.append('  return r;')
    out.append('}')
    return '\n'.join(out) + '\n'


def main():
    src, out_dir, prefix = sys.argv[1], pathlib.Path(sys.argv[2]), sys.argv[3]
    passes = parse(src)
    out_dir.mkdir(parents=True, exist_ok=True)
    for i, p in enumerate(passes):
        (out_dir / f'{prefix}{i}.hlsl').write_text(emit(p, i, pathlib.Path(src).name), newline='\n')
    print(f'{src}: {len(passes)} passes -> {out_dir}/{prefix}0..{len(passes) - 1}.hlsl')


if __name__ == '__main__':
    main()
